// Слои, а не статусы техники: люди (бирюзовые — решение Юлая 25.10) и легковые (фон, без подписи).
export const LAYERS = [
  { key: "person", word: "человек",  long: "люди — отдельный слой, без имён", video: "#4FC2C4", ink: "#16797B", icon: "person" },
  { key: "car",    word: "легковая", long: "легковые — фон, без подписи",     video: "#C3C9D1", ink: "#6B737D", icon: "car" },
];
// Выбор — отдельный слой: белое кольцо и приглушение остальных; статус-цвет НЕ перекрашивает.
export const SELECT = { ring: "#FFFFFF", dimOthers: 0.45 };
// Числовые правила (для пульта): линия 1,5–2 px + обводка 1 px #0B0C0E 60 %; уголок = clamp(6, 22 % стороны, 18) px;
// подпись 12–13 px, отступ от рамки 4 px, подложка #0B0C0E 78 %; меньше 600 px ширины окна — подпись сворачивается в значок + номер.
export const ALL = [...STATES, ...LAYERS];
export const byKey = Object.fromEntries(ALL.map((s) => [s.key, s]));

// CSS-переменные из того же списка — легенда, рамка и список не могут разойтись.
// На тёмной странице статус текстом берёт цвет кадра (светлый), на светлой — тёмный ink (≥ 4,5:1).
export function applyTokens(doc = document) {
  const light = ALL.map((s) => `--st-${s.key}:${s.video};--st-${s.key}-ink:${s.ink};`).join("");
  const dark = ALL.map((s) => `--st-${s.key}-ink:${s.video};`).join("");
  const el = doc.createElement("style");
  el.id = "st-tokens";
  el.textContent = `:root{${light}--st-select:${SELECT.ring}} :root[data-theme="dark"]{${dark}}`;
  doc.head.append(el);
}
